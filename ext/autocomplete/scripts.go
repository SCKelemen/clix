package autocomplete

import (
	"fmt"
	"strings"
)

// The scripts below are thin wrappers: they pass the command line to the
// program's hidden __complete command and hand its answer to the shell.
// Command names, flag names and descriptions never appear in them, so
// nothing in the command tree can end up as shell code, and no script uses
// eval. The placeholders (@NAME@ and so on) are replaced by script.

// bashScript implements the protocol for bash 3.2 and later, with or
// without the bash-completion package.
//
// See "Programmable Completion" and "Programmable Completion Builtins" in
// the bash manual:
// https://www.gnu.org/software/bash/manual/html_node/Programmable-Completion.html
// https://www.gnu.org/software/bash/manual/html_node/Programmable-Completion-Builtins.html
const bashScript = `# bash completion for @NAME@                                -*- shell-script -*-
#
# Generated by "@NAME@ autocomplete bash". Candidates come from the program
# itself (its hidden __complete command), so they always match the installed
# version. Works with bash 3.2 and later, with or without bash-completion.

@FUNC@() {
    # $2 is the text readline replaces: the end of the word after the last
    # word-break character in COMP_WORDBREAKS (such as = and :).
    local cur=${2-${COMP_WORDS[COMP_CWORD]}} prog=${COMP_WORDS[0]}
    local line out item directive quote i n
    local -a lines
    COMPREPLY=()
    case $prog in
        "~/"*) prog=$HOME/${prog#"~/"} ;;
    esac
    if [[ -n ${COMP_LINE+set} ]]; then
        line=${COMP_LINE:0:COMP_POINT}
    else
        for (( i = 0; i <= COMP_CWORD; i++ )); do
            line+=${line:+ }${COMP_WORDS[i]}
        done
    fi
    out=$("$prog" __complete --shell bash "--cur=$cur" "--line=$line" 2>/dev/null) || return 0
    while IFS= read -r item; do
        lines[${#lines[@]}]=$item
    done <<< "$out"
    n=${#lines[@]}
    (( n > 0 )) || return 0
    directive=${lines[n-1]}
    case $directive in
        :files | :nofiles) ;;
        *) return 0 ;;
    esac
    for (( i = 0; i < n - 1; i++ )); do
        COMPREPLY[i]=${lines[i]}
    done
    if (( n == 1 )) && [[ $directive == :files ]]; then
        # bash 4 and later: let readline complete file names.
        compopt -o default 2>/dev/null && return 0
        # bash 3.2 has no compopt: list them with compgen. Inside quotes
        # readline closes the quote itself, so only bare words are escaped.
        i=$(( ${#line} - ${#cur} - 1 ))
        quote=
        (( i >= 0 )) && quote=${line:i:1}
        while IFS= read -r item; do
            [[ -n $item ]] || continue
            [[ -d $item ]] && item=$item/
            case $quote in
                \' | \") ;;
                *) printf -v item '%q' "$item" ;;
            esac
            COMPREPLY[${#COMPREPLY[@]}]=$item
        done <<< "$(compgen -f -- "$cur")"
    fi
    return 0
}

complete -F '@FUNC@' @QNAME@
`

// zshScript implements the protocol for zsh. It works both when sourced
// after compinit and when autoloaded from $fpath as @FUNC@: the first call
// of the autoloaded function defines the real one and runs it.
//
// See "Completion System" in the zsh manual, in particular #compdef,
// compdef, _describe and _files:
// https://zsh.sourceforge.io/Doc/Release/Completion-System.html
const zshScript = `#compdef @COMPDEF@
# zsh completion for @NAME@.
#
# Generated by "@NAME@ autocomplete zsh". Candidates come from the program
# itself (its hidden __complete command), so they always match the installed
# version.

@FUNC@() {
  local prog cur directive
  local -a out candidates
  prog=${(Q)words[1]}
  [[ $prog == '~/'* ]] && prog=$HOME/${prog#'~/'}
  # PREFIX is the word up to the cursor, without its opening quote.
  if [[ $compstate[quote] == "'" ]]; then
    cur=$PREFIX
  else
    cur=${(Q)PREFIX}
  fi
  out=("${(@f)$("$prog" __complete --shell zsh "--cur=$cur" -- "$prog" "${(@Q)words[2,CURRENT-1]}" 2>/dev/null)}")
  directive=${out[-1]}
  [[ $directive == :files || $directive == :nofiles ]] || return 1
  candidates=("${(@)out[1,-2]}")
  if (( ${#candidates} )) && _describe -t values 'value' candidates; then
    return 0
  fi
  if [[ $directive == :files ]]; then
    _files
    return
  fi
  return 1
}

compdef @FUNC@ @QNAME@

if [[ ${funcstack[1]} == @FUNC@ ]]; then
  @FUNC@ "$@"
fi
`

// fishScript implements the protocol for fish 3 and later.
//
// See the fish documentation of complete and commandline:
// https://fishshell.com/docs/current/cmds/complete.html
// https://fishshell.com/docs/current/cmds/commandline.html
const fishScript = `# fish completion for @NAME@.
#
# Generated by "@NAME@ autocomplete fish". Candidates come from the program
# itself (its hidden __complete command), so they always match the installed
# version.

function @FUNC@
    set -l tokens (commandline -opc)
    set -l cur (commandline -ct)
    set -q tokens[1]; or return 0
    set -l out (command $tokens[1] __complete --shell fish "--cur=$cur" -- $tokens 2>/dev/null)
    set -q out[1]; or return 0
    set -l directive $out[-1]
    set -e out[-1]
    switch $directive
        case :files :nofiles
        case '*'
            return 0
    end
    if set -q out[1]
        printf '%s\n' $out
    else if test "$directive" = :files
        __fish_complete_path "$cur"
    end
end

complete -c @QNAME@ -f -a '(@FUNC@)'
`

// powershellScript implements the protocol for Windows PowerShell 5.1 and
// PowerShell 7.
//
// See Register-ArgumentCompleter and CompletionResult:
// https://learn.microsoft.com/powershell/module/microsoft.powershell.core/register-argumentcompleter
// https://learn.microsoft.com/dotnet/api/system.management.automation.completionresult
const powershellScript = `# PowerShell completion for @NAME@.
#
# Generated by "@NAME@ autocomplete powershell". Candidates come from the
# program itself (its hidden __complete command), so they always match the
# installed version.

Register-ArgumentCompleter -Native -CommandName @PSNAMES@ -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)

    # The words before the one being completed, with quotes removed.
    $words = @()
    foreach ($element in $commandAst.CommandElements) {
        if ($element.Extent.EndOffset -ge $cursorPosition) { break }
        if ($element -is [System.Management.Automation.Language.StringConstantExpressionAst]) {
            $words += $element.Value
        } else {
            $words += $element.Extent.Text
        }
    }
    if ($words.Count -eq 0) { return }

    # Each word goes in its own --word= argument: Windows PowerShell drops
    # empty arguments and may drop a bare -- before a native command.
    $program = $words[0]
    $arguments = @('__complete', '--shell', 'powershell', "--cur=$wordToComplete")
    foreach ($word in $words) { $arguments += "--word=$word" }
    $lines = @(& $program @arguments 2>$null)
    if ($lines.Count -eq 0) { return }
    $directive = [string]$lines[-1]
    if ($directive -ne ':files' -and $directive -ne ':nofiles') { return }

    $results = @()
    for ($i = 0; $i -lt $lines.Count - 1; $i++) {
        $fields = ([string]$lines[$i]).Split([char]9)
        if ($fields.Count -ne 3) { continue }
        $type = 'ParameterValue'
        if ($fields[1].StartsWith('-')) { $type = 'ParameterName' }
        $results += [System.Management.Automation.CompletionResult]::new($fields[0], $fields[1], $type, $fields[2])
    }
    if ($results.Count -gt 0) { return $results }
    # With no result PowerShell completes file names; an empty string stops it.
    if ($directive -eq ':nofiles') { return '' }
}
`

// shells lists the supported shells, as accepted by the autocomplete
// command.
var shells = []string{"bash", "zsh", "fish", "powershell"}

// script returns the completion script for shell, for a program called
// name. All placeholders are replaced in one pass, so a name that looks
// like a placeholder is not expanded again.
func script(name, shell string) (string, error) {
	shell, err := normalizeShell(shell, false)
	if err != nil {
		return "", err
	}
	id := identifier(name)
	common := []string{
		"@NAME@", commentSafe(name),
		"@COMPDEF@", strings.Join(strings.Fields(commentSafe(name)), "_"),
	}
	var tmpl string
	var pairs []string
	switch shell {
	case "bash":
		tmpl = bashScript
		pairs = []string{"@FUNC@", "_" + id + "_completions", "@QNAME@", shellSingleQuote(name)}
	case "zsh":
		tmpl = zshScript
		pairs = []string{"@FUNC@", "_" + id, "@QNAME@", shellSingleQuote(name)}
	case "fish":
		tmpl = fishScript
		pairs = []string{"@FUNC@", "__" + id + "_clix_complete", "@QNAME@", fishQuote(name)}
	case "powershell":
		tmpl = powershellScript
		pairs = []string{"@PSNAMES@", psQuote(name) + ", " + psQuote(name+".exe")}
	default:
		return "", fmt.Errorf("unsupported shell: %s", shell)
	}
	return strings.NewReplacer(append(common, pairs...)...).Replace(tmpl), nil
}
